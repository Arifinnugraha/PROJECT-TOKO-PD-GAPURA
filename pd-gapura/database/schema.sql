-- Supabase menggunakan schema public untuk Data API.
CREATE TABLE IF NOT EXISTS public.users (
    id_user integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama varchar(120) NOT NULL,
    username varchar(60) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN ('pemilik', 'kasir')),
    status varchar(20) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'nonaktif'))
);

CREATE TABLE IF NOT EXISTS public.supplier (
    id_supplier integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_supplier varchar(150) NOT NULL,
    alamat text,
    kontak varchar(40),
    status varchar(20) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'nonaktif'))
);

CREATE TABLE IF NOT EXISTS public.barang (
    id_barang integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_barang varchar(40) NOT NULL UNIQUE,
    nama_barang varchar(160) NOT NULL,
    kategori varchar(100) NOT NULL,
    satuan varchar(30) NOT NULL DEFAULT 'pcs',
    harga_beli numeric(15,2) NOT NULL DEFAULT 0 CHECK (harga_beli >= 0),
    harga_satuan numeric(15,2) NOT NULL DEFAULT 0 CHECK (harga_satuan >= 0),
    stok integer NOT NULL DEFAULT 0 CHECK (stok >= 0),
    stok_minimum integer NOT NULL DEFAULT 0 CHECK (stok_minimum >= 0),
    lokasi_penyimpanan varchar(120),
    keterangan text,
    status varchar(20) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'nonaktif'))
);

COMMENT ON COLUMN public.barang.harga_satuan IS 'Harga jual per satuan';

CREATE TABLE IF NOT EXISTS public.barang_masuk (
    id_barang_masuk integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal_masuk date NOT NULL,
    id_supplier integer NOT NULL REFERENCES public.supplier(id_supplier),
    id_user integer NOT NULL REFERENCES public.users(id_user)
);

CREATE TABLE IF NOT EXISTS public.detail_barang_masuk (
    id_detail_barang_masuk integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_barang_masuk integer NOT NULL REFERENCES public.barang_masuk(id_barang_masuk),
    id_barang integer NOT NULL REFERENCES public.barang(id_barang),
    jumlah integer NOT NULL CHECK (jumlah > 0),
    harga_beli numeric(15,2) NOT NULL CHECK (harga_beli >= 0)
);

CREATE TABLE IF NOT EXISTS public.transaksi (
    id_transaksi integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal_transaksi timestamptz NOT NULL DEFAULT now(),
    id_user integer NOT NULL REFERENCES public.users(id_user),
    total numeric(15,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    status_transaksi varchar(20) NOT NULL DEFAULT 'Belum Lunas' CHECK (status_transaksi IN ('Lunas', 'Belum Lunas'))
);

CREATE TABLE IF NOT EXISTS public.detail_transaksi (
    id_detail_transaksi integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi integer NOT NULL REFERENCES public.transaksi(id_transaksi),
    id_barang integer NOT NULL REFERENCES public.barang(id_barang),
    jumlah integer NOT NULL CHECK (jumlah > 0),
    harga_satuan numeric(15,2) NOT NULL CHECK (harga_satuan >= 0),
    subtotal numeric(15,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE IF NOT EXISTS public.pembayaran (
    id_pembayaran integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi integer NOT NULL REFERENCES public.transaksi(id_transaksi),
    tanggal_pembayaran timestamptz NOT NULL DEFAULT now(),
    jumlah_bayar numeric(15,2) NOT NULL DEFAULT 0 CHECK (jumlah_bayar >= 0),
    metode_pembayaran varchar(40) NOT NULL,
    status_pembayaran varchar(20) NOT NULL DEFAULT 'Belum Lunas' CHECK (status_pembayaran IN ('Lunas', 'Belum Lunas'))
);

-- Tabel pendukung yang ditambahkan untuk kebutuhan SRS: logging dan request akses laporan.
CREATE TABLE IF NOT EXISTS public.aktivitas_log (
    id_log bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user integer NOT NULL REFERENCES public.users(id_user),
    aksi varchar(80) NOT NULL,
    deskripsi text,
    waktu timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.permintaan_akses_laporan (
    id_permintaan integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user integer NOT NULL REFERENCES public.users(id_user),
    alasan varchar(255) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'Menunggu' CHECK (status IN ('Menunggu', 'Disetujui', 'Ditolak')),
    diproses_oleh integer REFERENCES public.users(id_user),
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    diproses_pada timestamptz
);

-- Index untuk foreign key dan pencarian/filter data yang sering dipakai aplikasi.
CREATE INDEX IF NOT EXISTS idx_barang_status_nama ON public.barang(status, nama_barang);
CREATE INDEX IF NOT EXISTS idx_barang_masuk_tanggal ON public.barang_masuk(tanggal_masuk DESC);
CREATE INDEX IF NOT EXISTS idx_detail_barang_masuk_header ON public.detail_barang_masuk(id_barang_masuk);
CREATE INDEX IF NOT EXISTS idx_transaksi_tanggal ON public.transaksi(tanggal_transaksi DESC);
CREATE INDEX IF NOT EXISTS idx_transaksi_user ON public.transaksi(id_user);
CREATE INDEX IF NOT EXISTS idx_detail_transaksi_header ON public.detail_transaksi(id_transaksi);
CREATE INDEX IF NOT EXISTS idx_pembayaran_transaksi ON public.pembayaran(id_transaksi);
CREATE INDEX IF NOT EXISTS idx_aktivitas_log_waktu ON public.aktivitas_log(waktu DESC);
CREATE INDEX IF NOT EXISTS idx_permintaan_user_status ON public.permintaan_akses_laporan(id_user, status);

